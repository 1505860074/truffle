"""功能区命名规则：前端展示与代码共用一套名称，避免各处叫法不一。

规则：
- 名称 = 「用途核心词」+「区域性质后缀」，整体 2~4 字，只讲用途、不加「面板/窗口」等实现词；
- 后缀按区域性质三选一：
    · 「栏」= 操作 / 信息交互区（用户在这里输入、调节、与 AI 对话）；
    · 「区」= 内容展示区（用户在这里看结果、看图片）；
    · 「库」= 资源集合区（集中管理一组可切换的资源）。

示例：对话框 → **对话栏**；参数调试面板 → **参数栏**；图片预览 → **画布区**；
菜单条 → **菜单栏**；多图集合 → **文件库**。
"""

from __future__ import annotations

AREA_NAMES: dict[str, str] = {
    "menu": "菜单栏",
    "chat": "对话栏",
    "canvas": "画布区",
    "files": "文件库",
    "params": "参数栏",
}


def area_name(key: str) -> str:
    from .i18n import tr

    return tr(AREA_NAMES.get(key, key))
